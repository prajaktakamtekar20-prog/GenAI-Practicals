original_dim = 28 * 28
latent_dim = 2
batch_size = 128
epochs = 30

print("Original dimension:", original_dim)
print("Latent dimension:", latent_dim)

# Encoder

encoder_inputs = keras.Input(shape=(28, 28, 1), name="encoder_input")

x = layers.Flatten(name="flatten")(encoder_inputs)
x = layers.Dense(256, activation="relu", name="encoder_dense_1")(x)
x = layers.Dense(128, activation="relu", name="encoder_dense_2")(x)

z_mean = layers.Dense(latent_dim, name="z_mean")(x)
z_log_var = layers.Dense(latent_dim, name="z_log_var")(x)

encoder = keras.Model(
    encoder_inputs,
    [z_mean, z_log_var],
    name="encoder"
)

encoder.summary()

# Reparameterization function

def sample_latent(z_mean, z_log_var):
    epsilon = tf.random.normal(
        shape=tf.shape(z_mean),
        mean=0.0,
        stddev=1.0
    )
    sigma = tf.exp(0.5 * z_log_var)
    z = z_mean + sigma * epsilon
    return z

# Decoder

latent_inputs = keras.Input(
    shape=(latent_dim,),
    name="decoder_input"
)

# Layer 1
x = layers.Dense(
    128,
    activation="relu",
    name="decoder_dense_1"
)(latent_inputs)

# Layer 2
x = layers.Dense(
    256,
    activation="relu",
    name="decoder_dense_2"
)(x)

# Layer 3
x = layers.Dense(
    28 * 28,
    activation="sigmoid",
    name="decoder_output_flat"
)(x)   # <-- IMPORTANT

# Convert 784 values back to 28 × 28 × 1
decoder_outputs = layers.Reshape(
    (28, 28, 1),
    name="decoder_output"
)(x)

# Create Decoder model
decoder = keras.Model(
    latent_inputs,
    decoder_outputs,
    name="decoder"
)

decoder.summary()

# Complete VAE model

class VAE(keras.Model):
    def __init__(self, encoder, decoder, **kwargs):
        super().__init__(**kwargs)
        self.encoder = encoder
        self.decoder = decoder

        self.total_loss_tracker = keras.metrics.Mean(name="total_loss")
        self.reconstruction_loss_tracker = keras.metrics.Mean(
            name="reconstruction_loss"
        )
        self.kl_loss_tracker = keras.metrics.Mean(name="kl_loss")

    @property
    def metrics(self):
        return [
            self.total_loss_tracker,
            self.reconstruction_loss_tracker,
            self.kl_loss_tracker,
        ]

    def train_step(self, data):
        if isinstance(data, tuple):
            data = data[0]

        with tf.GradientTape() as tape:
            z_mean, z_log_var = self.encoder(data)
            z = sample_latent(z_mean, z_log_var)
            reconstruction = self.decoder(z)

            # Reconstruction loss
            bce = keras.losses.binary_crossentropy(
                data, reconstruction
            )
            reconstruction_loss = tf.reduce_sum(bce, axis=(1, 2))
            reconstruction_loss = tf.reduce_mean(reconstruction_loss)

            # KL divergence
            kl_loss = -0.5 * tf.reduce_sum(
                1 + z_log_var
                - tf.square(z_mean)
                - tf.exp(z_log_var),
                axis=1
            )
            kl_loss = tf.reduce_mean(kl_loss)

            total_loss = reconstruction_loss + kl_loss

        # Backpropagation
        grads = tape.gradient(total_loss, self.trainable_weights)

        # Weight update
        self.optimizer.apply_gradients(
            zip(grads, self.trainable_weights)
        )

        self.total_loss_tracker.update_state(total_loss)
        self.reconstruction_loss_tracker.update_state(reconstruction_loss)
        self.kl_loss_tracker.update_state(kl_loss)

        return {
            "loss": self.total_loss_tracker.result(),
            "reconstruction_loss": self.reconstruction_loss_tracker.result(),
            "kl_loss": self.kl_loss_tracker.result(),
        }

    def call(self, inputs):
        z_mean, z_log_var = self.encoder(inputs)
        z = sample_latent(z_mean, z_log_var)
        return self.decoder(z)


vae = VAE(encoder, decoder, name="vae")
vae.compile(
    optimizer=keras.optimizers.Adam(learning_rate=1e-3)
)

print("VAE created successfully.")

# Train

history = vae.fit(
    x_train,
    epochs=epochs,
    batch_size=batch_size
)

# Plot training losses

